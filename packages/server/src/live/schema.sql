-- Local and test fixture shaped like the sanitized live Ours catalog.
-- Refuses to run when those tables already exist, so it cannot reset a live database.
do $$
begin
  if to_regclass('public.ours_settings') is not null
     or to_regclass('public.ours_snapshots') is not null
     or to_regclass('public.ours_passkey_credentials') is not null then
    raise exception 'live fixture refused: existing Ours tables were left untouched';
  end if;
end $$;

create extension if not exists pgcrypto;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin nosuperuser nobypassrls; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin nosuperuser nobypassrls; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;

create table ours_auth_attempts (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  kind text not null,
  ok boolean not null
);

create table ours_backup_codes (
  id bigint generated by default as identity primary key,
  code_hash text not null unique,
  created_at timestamptz not null default now(),
  used_at timestamptz
);

create table ours_challenges (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind = any (array['reg', 'auth'])),
  challenge text not null,
  setup_code_id bigint,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz
);

create table ours_custom_items (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(name) >= 1 and length(name) <= 80),
  kind text not null check (kind = any (array['asset', 'liability'])),
  value numeric not null check (value >= 0),
  note text check (note is null or length(note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table ours_device_setup_codes (
  id bigint generated by default as identity primary key,
  code_hash text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz
);

create table ours_fix_rules (
  id uuid primary key default gen_random_uuid(),
  match text not null check (length(match) >= 2 and length(match) <= 80),
  category text not null check (length(category) >= 1 and length(category) <= 40),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index ours_fix_rules_match_uq on ours_fix_rules (lower(match));

create table ours_passkey_credentials (
  id text primary key,
  public_key text not null,
  counter bigint not null default 0,
  transports text[] not null default '{}',
  device_name text not null default 'Passkey',
  created_at timestamptz not null default now(),
  last_used_at timestamptz
);

create table ours_refresh_requests (
  id bigint generated by default as identity primary key,
  requested_at timestamptz not null default now(),
  status text not null default 'open' check (status = any (array['open', 'done', 'failed'])),
  closed_at timestamptz,
  note text
);

create table ours_sessions (
  token_hash text primary key,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  last_seen_at timestamptz not null default now(),
  via text not null
);

create table ours_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table ours_snapshots (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  as_of timestamptz not null,
  data jsonb not null,
  report jsonb not null
);

do $$
declare table_name text;
begin
  for table_name in
    select tablename from pg_tables
    where schemaname = 'public' and tablename like 'ours\_%' escape '\'
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from public', table_name);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on table public.%I from anon', table_name);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on table public.%I from authenticated', table_name);
    end if;
    if exists (select 1 from pg_roles where rolname = 'service_role') then
      execute format('grant select, insert, update, delete on table public.%I to service_role', table_name);
    end if;
  end loop;
end $$;
